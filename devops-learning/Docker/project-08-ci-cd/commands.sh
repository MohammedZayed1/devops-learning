#!/bin/bash

# ============================================================
# Project 08 - CI/CD with GitHub Actions and Docker
# ============================================================

# ------------------------------------------------------------
# 1. Navigate to the project
# ------------------------------------------------------------

cd ~/DevOps_Projects/devops-learning/Docker/project-08-ci-cd


# ------------------------------------------------------------
# 2. Check Git repository status
# ------------------------------------------------------------

git status


# ------------------------------------------------------------
# 3. Check current branch
# ------------------------------------------------------------

git branch --show-current


# ------------------------------------------------------------
# 4. Create the feature branch
# ------------------------------------------------------------

git checkout -b feature/docker-project-08-ci-cd


# ------------------------------------------------------------
# 5. Navigate to the Node.js application
# ------------------------------------------------------------

cd app


# ------------------------------------------------------------
# 6. Install Node.js dependencies
# ------------------------------------------------------------

npm ci


# ------------------------------------------------------------
# 7. Run application tests
# ------------------------------------------------------------

npm test


# ------------------------------------------------------------
# 8. Build the Docker image locally
# ------------------------------------------------------------

cd ..

docker build -t devops-ci-cd-demo:local .


# ------------------------------------------------------------
# 9. Run the Docker container
# ------------------------------------------------------------

docker run --rm -p 3000:3000 devops-ci-cd-demo:local


# ------------------------------------------------------------
# 10. Check Docker images
# ------------------------------------------------------------

docker images


# ------------------------------------------------------------
# 11. Check GitHub Actions workflow
# ------------------------------------------------------------

cd ~/DevOps_Projects

cat .github/workflows/docker-ci.yml


# ------------------------------------------------------------
# 12. Check Git status before committing
# ------------------------------------------------------------

git status


# ------------------------------------------------------------
# 13. Add project changes
# ------------------------------------------------------------

git add .


# ------------------------------------------------------------
# 14. Commit changes
# ------------------------------------------------------------

git commit -m "Add Docker CI workflow"


# ------------------------------------------------------------
# 15. Push the feature branch
# ------------------------------------------------------------

git push -u origin feature/docker-project-08-ci-cd


# ------------------------------------------------------------
# 16. Fetch remote changes
# ------------------------------------------------------------

git fetch origin


# ------------------------------------------------------------
# 17. Check remote branches
# ------------------------------------------------------------

git branch -a


# ------------------------------------------------------------
# 18. Check recent commits
# ------------------------------------------------------------

git log --oneline --decorate -5


# ------------------------------------------------------------
# 19. Check GitHub Actions workflow location
# ------------------------------------------------------------

git ls-tree -r HEAD --name-only | grep ".github/workflows"


# ------------------------------------------------------------
# 20. Create Pull Request
# ------------------------------------------------------------

# Create the Pull Request through GitHub:
#
# feature/docker-project-08-ci-cd
#              ↓
#             main


# ------------------------------------------------------------
# 21. Merge Pull Request
# ------------------------------------------------------------

# After the CI checks pass and the Pull Request is reviewed,
# merge the Pull Request into main through GitHub.
